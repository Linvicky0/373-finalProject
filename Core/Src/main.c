uint32_t update_ccr(uint32_t originalVal, uint32_t target) {
	if (target > originalVal) {
		return originalVal + 5;
	}
	else if (target < originalVal) {
		return originalVal - 5;
	}
	return originalVal;
}



void move_hand(Gesture robotMove)
{
	 uint32_t thumb_target;
	 uint32_t index_middle_target;
	 uint32_t ring_pinky_target;
	//  CCR 50 = 0 degrees, CCR 150 = 90 degrees, CCR 250 = 180 degrees

	  if (robotMove == ROCK) { // thumb ccr to 250, other timers' CCR set to 50
		  thumb_target = 250;
		  index_middle_target = 50;
		  ring_pinky_target = 50;
	}
	 else if (robotMove == PAPER) { // thumb ccr to 50, other timers' CCR set to 250
		  thumb_target = 50;
		  index_middle_target = 250;
		  ring_pinky_target = 250;
	 }
	 else if (robotMove == SCISSORS) {
		 thumb_target = 250;
		 index_middle_target = 250;
		 ring_pinky_target = 50;
	 }
	 else if (robotMove == NOCHOICE) {
		 thumb_target = 150;
		 index_middle_target = 125;
		 ring_pinky_target = 125;
	  }
	  uint32_t thumb_ccr =  htim1.Instance->CCR4;
	  uint32_t index_middle_ccr = htim4.Instance->CCR2;
	  uint32_t ring_pinky_ccr = htim4.Instance->CCR4;

	  while (thumb_ccr != thumb_target || (index_middle_target != index_middle_ccr) || (ring_pinky_target != ring_pinky_ccr)) {
		 if (thumb_ccr != thumb_target) {
			 __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_4, update_ccr(thumb_ccr, thumb_target));
		 }
		 if (index_middle_ccr != index_middle_target) {

			 __HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_2, update_ccr(index_middle_ccr, index_middle_target));
		 }
		 else if (ring_pinky_ccr != ring_pinky_target) {

			 __HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_4, update_ccr(ring_pinky_ccr, ring_pinky_target));
		 }
		thumb_ccr =  htim1.Instance->CCR4;
		index_middle_ccr = htim4.Instance->CCR2;
		ring_pinky_ccr = htim4.Instance->CCR4;
		HAL_Delay(1);
	}

}

