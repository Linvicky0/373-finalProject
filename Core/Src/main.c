/* audio clips generated from WAVs */
const uint8_t win_clip_u8[] = {
    0,  64, 128, 192, 255, 192, 128, 64,
    0,  64, 128, 192, 255, 192, 128, 64,
    0,  64, 128, 192, 255, 192, 128, 64,
    0,  64, 128, 192, 255, 192, 128, 64
};
const uint32_t win_clip_u8_len = sizeof(win_clip_u8) / sizeof(win_clip_u8[0]);

/* Lose: different repeating pattern */
const uint8_t lose_clip_u8[] = {
    255, 192, 128, 64, 0, 64, 128, 192,
    255, 192, 128, 64, 0, 64, 128, 192,
    255, 192, 128, 64, 0, 64, 128, 192,
    255, 192, 128, 64, 0, 64, 128, 192
};
const uint32_t lose_clip_u8_len = sizeof(lose_clip_u8) / sizeof(lose_clip_u8[0]);
/* 12-bit expanded buffers in RAM (size must be >= clip length) */
static uint16_t win_clip_12[40960];
static uint16_t lose_clip_12[40960];

static uint32_t win_len_12 = 0;
static uint32_t lose_len_12 = 0;

extern DAC_HandleTypeDef hdac1;
extern TIM_HandleTypeDef htim6;


static void convert_u8_to_12bit(const uint8_t *src, uint32_t len,
                                uint16_t *dst, uint32_t *out_len)
{
    for (uint32_t i = 0; i < len; ++i) {
        // Scale: 8-bit range to 12-bit range
        dst[i] = ((uint16_t)src[i]) * 16;  // 255 * 16 ≈ 4080
    }
    *out_len = len;
}

void Audio_Init(void)
{
    // Convert both clips to 12-bit buffers
    convert_u8_to_12bit(win_clip_u8,  win_clip_u8_len,  win_clip_12,  &win_len_12);
    convert_u8_to_12bit(lose_clip_u8, lose_clip_u8_len, lose_clip_12, &lose_len_12);

    // Start DAC (no DMA yet)
    HAL_DAC_Start(&hdac1, DAC_CHANNEL_1);
}


static const uint16_t *current_buf = NULL;
static uint32_t current_len = 0;
static uint8_t audio_busy = 0;

static void Audio_PlayBuffer(const uint16_t *buf, uint32_t len)
{
    if (audio_busy) {
        // Optional: ignore if something already playing,
        // or stop and restart. Here we just ignore.
        return;
    }

    current_buf = buf;
    current_len = len;
    audio_busy = 1;

    // Make sure timer is stopped before we start
    HAL_TIM_Base_Stop(&htim6);

    // Start timer that triggers DAC at 16 kHz
    HAL_TIM_Base_Start(&htim6);

    // Start DAC DMA in 12-bit right-aligned mode
    HAL_DAC_Start_DMA(&hdac1,
                      DAC_CHANNEL_1,
                      (uint32_t *)current_buf,
                      current_len,
                      DAC_ALIGN_12B_R);
}

void Audio_PlayWin(void)
{
    Audio_PlayBuffer(win_clip_12, win_len_12);
}

void Audio_PlayLose(void)
{
    Audio_PlayBuffer(lose_clip_12, lose_len_12);
}

// Called when DMA transfer for DAC channel 1 completes
void HAL_DAC_ConvCpltCallbackCh1(DAC_HandleTypeDef *hdac)
{
    if (hdac->Instance == DAC1) {
        // Stop timer and DMA when clip ends
        HAL_TIM_Base_Stop(&htim6);
        HAL_DAC_Stop_DMA(hdac, DAC_CHANNEL_1);
        audio_busy = 0;
    }
}

