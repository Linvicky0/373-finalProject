static uint16_t audio_buffer_12[80000];  // Safe size
static uint32_t rps_len_12 = 0;

void Audio_Init(void)
{
    HAL_DAC_Start(&hdac1, DAC_CHANNEL_1);

    int16_t* src = (int16_t*)rps_clip_u8;  // Signed, not unsigned
    rps_len_12 = sizeof(rps_clip_u8) / 2;

    for (uint32_t i = 0; i < rps_len_12; i++) {
        audio_buffer_12[i] = (uint16_t)((src[i] + 32768) >> 4);
    }
}

static const uint16_t *current_buf = NULL;
static uint32_t current_len = 0;
static uint8_t audio_busy = 0;

static void Audio_PlayBuffer(const uint16_t *buf, uint32_t len)
{
	 printf("PlayBuffer called, len=%lu\r\n", len);
    if (audio_busy) {
    	printf("BUSY - returning\r\n");

        return;
    }

    current_buf = buf;
    current_len = len;
    audio_busy = 1;

    // Make sure timer is stopped before we start
    HAL_TIM_Base_Stop(&htim6);

    // Start timer that triggers DAC at 16 kHz
    HAL_TIM_Base_Start(&htim6);

    printf("Before DMA start\r\n");

    // Start DAC DMA in 12-bit right-aligned mode
    HAL_DAC_Start_DMA(&hdac1,
                      DAC_CHANNEL_1,
                      (uint32_t *)current_buf,
                      current_len,
                      DAC_ALIGN_12B_R);

    printf("After DMA start\r\n");
}


void Audio_PlayRPS(void)
{
	   printf("audio_busy = %d\r\n", audio_busy);
    Audio_PlayBuffer(audio_buffer_12, rps_len_12);
}
