void fill_buffer(float sample_buffer[]) {
	uint8_t isReady = 0;

	    // Wait for sensor data to be ready
	    do {
	        status = vl53l7cx_check_data_ready(&Dev, &isReady);
	        HAL_Delay(10);
	    } while(!isReady);

	    // Get ranging data from sensor
	    status = vl53l7cx_get_ranging_data(&Dev, &Results);

	    if(status == 0) {
	        // Fill buffer with distance data (64 zones)
	        for(int i = 0; i < 64; i++) {
	            uint16_t distance = Results.distance_mm[i];
	            uint8_t target_status = Results.target_status[i];

	            // VL53L7CX target_status values:
	            // 5 = Valid ranging
	            // 9 = Valid ranging with signal rate too low
	            // Others = Invalid (no target, wraparound, etc.)

	            if(target_status == 5 || target_status == 9) {
	                // Valid reading
	                if(distance > 255) {
	                    sample_buffer[i] = 255.0;
	                } else {
	                    sample_buffer[i] = (float)distance;
	                }
	            } else {
	                // Invalid reading - use max value to indicate "no object"
	                sample_buffer[i] = 255.0;
	            }
	        }

	        //Send all 64 data points in CSV format
//	        for(int i = 0; i < 64; i++) {
//	            printf("%.2f", sample_buffer[i]);
//	            if(i < 63) {
//	                printf(",");
//	            }
//	        }
//	        printf("\r\n");
	    } else {
	        printf("Error reading sensor: %d\r\n", status);
	    }
}


